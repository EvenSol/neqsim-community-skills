"""Exact solids from a scene: a CadQuery script (STEP, STL, glTF) and an OpenSCAD file.

Both backends follow the same pattern as the rest of the NeqSim coupling
skills: the model is written as a self-contained, readable script first, and
run only if the tool is present. The script is the deliverable either way - it
can be opened, edited and run on another machine.

CAD solids carry geometry and colour, not calculated fields. A tube coloured by
temperature becomes a plain tube here; draw the coloured result with the PyVista
backend and use these exports for the geometry.
"""

from __future__ import annotations

import json
import subprocess
import sys
from importlib.util import find_spec
from pathlib import Path
from shutil import which
from typing import Any, Sequence

from .mesh import axis_rotation
from .model import RenderOutcome, Scene

_MAX_TUBE_POINTS = 120
_PAD_FRACTION = 0.02


def _clip_box(
    scene: Scene, clip: Sequence[float | None], inset: float = 0.0
) -> tuple[list[float], list[float]]:
    """Finite ``(minimum corner, size)`` of a clip box.

    Open sides are closed just outside the scene. ``inset`` moves every stated
    cut plane inwards by that distance (see :func:`openscad_script`).
    """
    b = scene.bounds()
    pad = _PAD_FRACTION * max(b[1] - b[0], b[3] - b[2], b[5] - b[4]) + 0.01
    corner, size = [], []
    for axis in range(3):
        low, high = clip[2 * axis], clip[2 * axis + 1]
        low = b[2 * axis] - pad if low is None else float(low) + inset
        high = b[2 * axis + 1] + pad if high is None else float(high) - inset
        corner.append(float(low))
        size.append(max(float(high) - float(low), 1e-9))
    return corner, size


def _decimate(points: Sequence[Sequence[float]]) -> list[list[float]]:
    step = max(1, -(-len(points) // _MAX_TUBE_POINTS))
    kept = [list(map(float, p)) for p in points[::step]]
    if kept[-1] != list(map(float, points[-1])):
        kept.append(list(map(float, points[-1])))
    return kept


def _parts(scene: Scene, stagger: float = 0.0) -> list[dict[str, Any]]:
    """Scene primitives as plain data for the generated scripts."""
    parts = []
    clipped = 0
    for primitive in scene.primitives:
        if primitive.kind == "ribbon":
            continue  # a zero-thickness strip is not a solid
        data = primitive.to_dict()
        data.pop("scalars")
        part: dict[str, Any] = {
            "name": data["name"],
            "kind": data["kind"],
            "role": data["role"],
            "color": data["color"],
            "opacity": data["opacity"],
        }
        p = data["params"]
        if primitive.kind == "revolved":
            profile = [[float(a), float(r)] for a, r in p["profile"]]
            if len(profile) > 1 and profile[0] == profile[-1]:
                profile = profile[:-1]
            rotation_axis, angle = axis_rotation(p["axis"])
            part.update(profile=profile, origin=p["origin"], rot_axis=rotation_axis, rot_deg=angle)
        elif primitive.kind == "cylinder":
            rotation_axis, angle = axis_rotation(p["axis"])
            part.update(
                base=p["base"],
                radius=p["radius"],
                height=p["height"],
                rot_axis=rotation_axis,
                rot_deg=angle,
            )
        elif primitive.kind == "box":
            part.update(
                center=p["center"], size=p["size"], rotation_z_deg=p.get("rotation_z_deg", 0.0)
            )
        elif primitive.kind == "tube":
            part.update(points=_decimate(p["points"]), radius=p["radius"])
        if primitive.clip is not None:
            corner, size = _clip_box(scene, primitive.clip, inset=stagger * clipped)
            part.update(clip_corner=corner, clip_size=size)
            clipped += 1
        parts.append(part)
    return parts


def _identifier(name: str, used: set[str]) -> str:
    base = "".join(ch if ch.isalnum() else "_" for ch in name).strip("_") or "part"
    if base[0].isdigit():
        base = "p_" + base
    candidate, counter = base, 2
    while candidate in used:
        candidate = f"{base}_{counter}"
        counter += 1
    used.add(candidate)
    return candidate


# ------------------------------------------------------------------- CadQuery

_CADQUERY_TEMPLATE = '''"""CadQuery model generated by neqsim-engineering-3d-illustration.

__CAPTION__

Run:  python __SCRIPT__ [output_dir]
Writes __NAME__.step, __NAME__.stl and (when supported) __NAME__.glb.
"""

import json
import sys
from pathlib import Path

import cadquery as cq

PARTS = json.loads(r"""
__PARTS__
""")


def oriented(shape, part, origin):
    if part.get("rot_deg"):
        shape = shape.rotate((0, 0, 0), tuple(part["rot_axis"]), part["rot_deg"])
    return shape.translate(tuple(origin))


def build(part):
    kind = part["kind"]
    if kind == "revolved":
        # (axial, radius) outline drawn as (radius, axial) on XZ, revolved about Z.
        outline = [(r, a) for a, r in part["profile"]]
        shape = cq.Workplane("XZ").polyline(outline).close().revolve(360, (0, 0, 0), (0, 1, 0))
        shape = oriented(shape, part, part["origin"])
    elif kind == "cylinder":
        shape = cq.Workplane("XY").circle(part["radius"]).extrude(part["height"])
        shape = oriented(shape, part, part["base"])
    elif kind == "box":
        shape = cq.Workplane("XY").box(*part["size"])
        shape = shape.rotate((0, 0, 0), (0, 0, 1), part["rotation_z_deg"])
        shape = shape.translate(tuple(part["center"]))
    elif kind == "tube":
        solids = []
        points = [cq.Vector(*p) for p in part["points"]]
        for start, end in zip(points[:-1], points[1:]):
            run = end - start
            solids.append(cq.Solid.makeCylinder(part["radius"], run.Length, start, run))
            solids.append(cq.Solid.makeSphere(part["radius"]).translate(end))
        shape = cq.Workplane("XY").newObject([cq.Compound.makeCompound(solids)])
    else:
        raise ValueError("unknown part kind " + kind)
    if "clip_corner" in part:
        size = part["clip_size"]
        corner = part["clip_corner"]
        cutter = cq.Workplane("XY").box(*size, centered=False).translate(tuple(corner))
        shape = shape.intersect(cutter)
    return shape


def main(output_dir="."):
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    assembly = cq.Assembly(name="__NAME__")
    for part in PARTS:
        shape = build(part)
        if not shape.vals() or shape.val().Volume() <= 0.0:
            continue  # clipped away entirely
        r, g, b = part["color"]
        assembly.add(shape, name=part["id"], color=cq.Color(r, g, b, part["opacity"]))
    assembly.save(str(out / "__NAME__.step"))
    cq.exporters.export(assembly.toCompound(), str(out / "__NAME__.stl"))
    try:
        assembly.save(str(out / "__NAME__.glb"))
    except Exception as error:  # glTF export is a convenience
        print("glb export skipped:", error)
    print("wrote", out / "__NAME__.step")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
'''


def cadquery_script(scene: Scene) -> str:
    """A self-contained CadQuery script that rebuilds the scene as exact solids."""
    used: set[str] = set()
    parts = _parts(scene)
    for part in parts:
        part["id"] = _identifier(part["name"], used)
    return (
        _CADQUERY_TEMPLATE.replace("__CAPTION__", scene.caption())
        .replace("__SCRIPT__", f"{scene.name}_cadquery.py")
        .replace("__NAME__", scene.name)
        .replace("__PARTS__", json.dumps(parts, indent=1))
    )


def export_cadquery(
    scene: Scene, output_dir: str | Path, *, timeout_s: float = 600.0
) -> RenderOutcome:
    """Write the CadQuery script and, if CadQuery is installed, export STEP/STL/glTF."""
    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    script = directory / f"{scene.name}_cadquery.py"
    script.write_text(cadquery_script(scene), encoding="utf-8")
    command = f"python {script.name} ."
    if find_spec("cadquery") is None:
        return RenderOutcome(
            backend="cadquery",
            status="not_executed",
            files=(script,),
            command=f"pip install cadquery && {command}",
            message="CadQuery is not installed; the script was written but not run",
            caption=scene.caption(),
        )
    try:
        result = subprocess.run(
            [sys.executable, script.name, "."],
            cwd=directory,
            capture_output=True,
            text=True,
            timeout=timeout_s,
        )
    except subprocess.TimeoutExpired:
        return RenderOutcome(
            "cadquery",
            "failed",
            (script,),
            command,
            f"timed out after {timeout_s:.0f} s",
            scene.caption(),
        )
    if result.returncode != 0:
        return RenderOutcome(
            "cadquery",
            "failed",
            (script,),
            command,
            (result.stderr or result.stdout).strip()[-600:],
            scene.caption(),
        )
    files = [script] + [
        path
        for path in (directory / f"{scene.name}.{ext}" for ext in ("step", "stl", "glb"))
        if path.exists()
    ]
    return RenderOutcome(
        backend="cadquery",
        status="completed",
        files=tuple(files),
        command=command,
        message="exported " + ", ".join(f.suffix.lstrip(".") for f in files[1:]),
        caption=scene.caption(),
    )


# ------------------------------------------------------------------- OpenSCAD


def _scad_number(value: float) -> str:
    return f"{float(value):.6g}"


def _scad_vector(values: Sequence[float]) -> str:
    return "[" + ", ".join(_scad_number(v) for v in values) + "]"


def openscad_script(scene: Scene, *, facets: int = 64) -> str:
    """A readable OpenSCAD file with one module per part.

    Parts cut by the same plane (a cutaway, a level) would have coplanar cut
    faces, which OpenSCAD's preview renders as flicker. Each part's cut planes
    are therefore moved inwards by a further 0.01 % of the scene size - well
    under a millimetre per part on a vessel - which is stated in the file.
    """
    used: set[str] = set()
    b = scene.bounds()
    stagger = 1e-4 * max(b[1] - b[0], b[3] - b[2], b[5] - b[4])
    lines = [
        "// OpenSCAD model generated by neqsim-engineering-3d-illustration",
        "// " + scene.caption(),
        "// Units: metres. Preview with F5; render with F6 before exporting STL.",
        f"// Cut planes are staggered by {stagger * 1000.0:.2g} mm per part to keep the preview clean.",
        f"$fn = {int(facets)};",
        "",
    ]
    calls = []
    for part in _parts(scene, stagger):
        identifier = _identifier(part["name"], used)
        orient = ""
        if part.get("rot_deg"):
            orient = (
                f"rotate(a={_scad_number(part['rot_deg'])}, v={_scad_vector(part['rot_axis'])}) "
            )
        if part["kind"] == "revolved":
            outline = ", ".join(_scad_vector((r, a)) for a, r in part["profile"])
            body = (
                f"translate({_scad_vector(part['origin'])}) {orient}"
                f"rotate_extrude(convexity=6) polygon([{outline}]);"
            )
        elif part["kind"] == "cylinder":
            body = (
                f"translate({_scad_vector(part['base'])}) {orient}"
                f"cylinder(h={_scad_number(part['height'])}, r={_scad_number(part['radius'])});"
            )
        elif part["kind"] == "box":
            body = (
                f"translate({_scad_vector(part['center'])}) "
                f"rotate([0, 0, {_scad_number(part['rotation_z_deg'])}]) "
                f"cube({_scad_vector(part['size'])}, center=true);"
            )
        else:
            radius = _scad_number(part["radius"])
            points = ", ".join(_scad_vector(p) for p in part["points"])
            body = (
                f"pts = [{points}];\n"
                f"    for (i = [0 : len(pts) - 2]) hull() {{\n"
                f"        translate(pts[i]) sphere(r={radius}, $fn=12);\n"
                f"        translate(pts[i + 1]) sphere(r={radius}, $fn=12);\n"
                f"    }}"
            )
        if "clip_corner" in part:
            body = (
                "intersection() {\n"
                f"        {body}\n"
                f"        translate({_scad_vector(part['clip_corner'])}) "
                f"cube({_scad_vector(part['clip_size'])});\n"
                "    }"
            )
        color = _scad_vector(list(part["color"]) + [part["opacity"]])
        lines.append(f"module {identifier}() {{  // {part['role']}: {part['name']}")
        lines.append(f"    {body}")
        lines.append("}")
        lines.append("")
        calls.append(f"color({color}) {identifier}();")
    lines.extend(calls)
    return "\n".join(lines) + "\n"


def export_openscad(
    scene: Scene,
    output_dir: str | Path,
    *,
    png: bool = True,
    stl: bool = False,
    image_size: tuple[int, int] = (1600, 1000),
    timeout_s: float = 600.0,
) -> RenderOutcome:
    """Write the ``.scad`` file and, if OpenSCAD is installed, a preview PNG and/or STL.

    The PNG is OpenSCAD's own preview (with colours). It needs a display;
    ``xvfb-run`` is used automatically when it is available and no display is set.
    A full STL render of a detailed scene can take minutes, so it is off by default.
    """
    import os

    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    scad = directory / f"{scene.name}.scad"
    scad.write_text(openscad_script(scene), encoding="utf-8")
    command = f"openscad -o {scene.name}.png --imgsize={image_size[0]},{image_size[1]} --viewall --autocenter {scad.name}"
    executable = which("openscad")
    if executable is None:
        return RenderOutcome(
            backend="openscad",
            status="not_executed",
            files=(scad,),
            command=command,
            message="OpenSCAD is not on PATH; the .scad file was written but not rendered",
            caption=scene.caption(),
        )
    files = [scad]
    problems = []
    jobs = []
    if png:
        prefix = []
        if not os.environ.get("DISPLAY") and which("xvfb-run"):
            prefix = ["xvfb-run", "-a"]
        jobs.append(
            (
                f"{scene.name}_openscad.png",
                prefix
                + [
                    executable,
                    "-o",
                    f"{scene.name}_openscad.png",
                    f"--imgsize={image_size[0]},{image_size[1]}",
                    "--viewall",
                    "--autocenter",
                    "--colorscheme=Tomorrow",
                    scad.name,
                ],
            )
        )
    if stl:
        jobs.append(
            (
                f"{scene.name}_openscad.stl",
                [executable, "-o", f"{scene.name}_openscad.stl", scad.name],
            )
        )
    for target, arguments in jobs:
        try:
            result = subprocess.run(
                arguments, cwd=directory, capture_output=True, text=True, timeout=timeout_s
            )
        except subprocess.TimeoutExpired:
            problems.append(f"{target}: timed out after {timeout_s:.0f} s")
            continue
        produced = directory / target
        if result.returncode == 0 and produced.exists() and produced.stat().st_size > 0:
            files.append(produced)
        else:
            problems.append(f"{target}: {(result.stderr or result.stdout).strip()[-300:]}")
    status = "completed" if len(files) > 1 or not jobs else "failed"
    message = "wrote " + ", ".join(f.name for f in files)
    if problems:
        message += "; " + "; ".join(problems)
    return RenderOutcome(
        backend="openscad",
        status=status,
        files=tuple(files),
        command=command,
        message=message,
        caption=scene.caption(),
    )
